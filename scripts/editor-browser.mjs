import { chromium, expect } from '@playwright/test'

export async function editorBrowserTest({ admin, theme, token }) {
  const browser = await chromium.launch()
  try {
    const context = await browser.newContext()
    await context.addCookies([
      { name: 'rp_session', value: token, url: admin, httpOnly: true, sameSite: 'Lax' },
      { name: 'rp_language', value: 'en', url: admin, sameSite: 'Lax' },
    ])
    const page = await context.newPage()
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    await page.goto(admin)
    await expect(page.getByRole('heading', { name: 'Contents', exact: true })).toBeVisible()
    await expect(page.locator('html')).toHaveAttribute('lang', 'en')
    await page.getByRole('button', { name: 'New content', exact: true }).click()
    await page.getByLabel('Type', { exact: true }).selectOption('post')
    await page.getByLabel('Content language', { exact: true }).last().selectOption('en')
    await page.getByLabel('Title', { exact: true }).fill('Browser Markdown')
    await page.getByLabel('Slug', { exact: true }).fill('browser-markdown')
    const source = page.locator('textarea[aria-label="Markdown content"]')
    await source.fill('## Browser heading\n\n**Bold** and *italic*\n\n- One\n- Two\n\n| Name | Value |\n| --- | --- |\n| Table | Kept |\n\n```rust\nlet x = 1;\n```\n\n<script>alert(1)</script>')
    await page.getByRole('button', { name: 'Visual', exact: true }).click()
    const visual = page.locator('[contenteditable="true"]')
    await expect(visual.locator('strong')).toHaveText('Bold')
    await expect(visual.locator('table')).toContainText('Kept')
    await visual.click()
    await visual.press('ControlOrMeta+End')
    await visual.press('Enter')
    await page.keyboard.insertText('Visual edit')
    await page.getByRole('button', { name: 'MD source', exact: true }).click()
    await expect(source).toHaveValue(/\*\*Bold\*\*/)
    await expect(source).toHaveValue(/Visual edit/)
    await expect(source).toHaveValue(/Kept/)
    await expect(source).toHaveValue(/```rust/)
    await page.getByRole('button', { name: 'Safe preview', exact: true }).click()
    await expect(page.locator('.markdown-body strong')).toHaveText('Bold')
    await expect(page.locator('.markdown-body script')).toHaveCount(0)
    await page.getByLabel('Status', { exact: true }).selectOption('published')
    const saved = page.waitForResponse(response => response.url().endsWith('/api/v1/contents') && response.request().method() === 'POST')
    await page.getByRole('button', { name: 'Save', exact: true }).click()
    expect((await saved).status()).toBe(201)
    await expect(page.getByRole('status').filter({ hasText: 'Saved: revision 1.' })).toBeVisible()
    await page.reload()
    await page.getByRole('button', { name: /Browser Markdown/ }).click()
    await expect(page.locator('textarea[aria-label="Markdown content"]')).toHaveValue(/Visual edit/)
    await page.getByRole('button', { name: 'Create Italiano translation', exact: true }).click()
    await expect(page.getByLabel('Content language', { exact: true }).last()).toHaveValue('it')
    await expect(page.getByLabel('Status', { exact: true })).toHaveValue('draft')
    await page.getByLabel('Title', { exact: true }).fill('Traduzione browser')
    await page.getByLabel('Slug', { exact: true }).fill('traduzione-browser')
    await page.getByRole('button', { name: 'Save', exact: true }).click()
    await expect(page.getByRole('status').filter({ hasText: 'Saved: revision 1.' })).toBeVisible()
    await page.getByLabel('Language', { exact: true }).selectOption('it')
    await expect(page.getByRole('button', { name: 'Nuovo contenuto', exact: true })).toBeVisible()
    await page.reload()
    await expect(page.locator('html')).toHaveAttribute('lang', 'it')
    const publicPage = await context.newPage()
    await publicPage.goto(`${theme}/en/browser-markdown`)
    await expect(publicPage.locator('article strong')).toHaveText('Bold')
    await expect(publicPage.locator('article script')).toHaveCount(0)
    await expect(publicPage.locator('article')).toContainText('Visual edit')
    expect(errors).toEqual([])
    console.log('Chromium passed: authenticated translated admin, Tiptap visual/Markdown roundtrip, sanitized preview, publish/reload, linked draft translation and persisted UI language.')
  } finally {
    await browser.close()
  }
}
